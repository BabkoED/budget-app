#!/usr/bin/env python3
"""Разбор палитры числами: гармония, различимость, цветовая слепота.

    python3 tools/palette-check.py

Зачем. Про цвета принято спорить словами — «тёплая», «гармоничная»,
«не сочетается». Спор словами не сходится никогда. Здесь считается то,
что считается:

  1. Светлота, насыщенность и тон каждого цвета в OKLab — видно, лежит ли
     палитра в одной системе или собрана по случаю.
  2. Различимость пар (ΔE в CIE Lab) — насколько два цвета вообще
     отличимы глазом.
  3. Три вида цветовой слепоты — не сливаются ли пары, которые НЕСУТ
     РАЗНЫЙ СМЫСЛ. Это главная часть: у 8% мужчин красно-зелёная пара
     не различается, а в приложении про деньги именно она значит
     «прибыло» и «потратил».

Метод симуляции: Viénot, Brettel & Mollon (1999), перевод в пространство
LMS и проекция на плоскость сохранившихся колбочек. Это стандартный
приближённый метод, тот же, что в инструментах проверки доступности.

Скрипт ничего не меняет — только считает.
"""
import math

# ── палитра приложения (держать в соответствии с :root в index.html) ──
PALETTE = {
    '--bg':        ('#131515', 'фон страницы'),
    '--card':      ('#182020', 'карточка'),
    '--pop':       ('#252C2C', 'всплывающее меню'),
    '--br':        ('#273030', 'граница'),
    '--t':         ('#EFF5F9', 'основной текст'),
    '--mt':        ('#949398', 'вторичный текст'),
    '--accent':    ('#635BFF', 'действие, заливка'),
    '--accent-tx': ('#A791FD', 'действие, текст на тёмном'),
    '--gd':        ('#30C97C', 'прибыло / в плюсе'),
    '--rd':        ('#FF4F47', 'перерасход / в минусе'),
}

# Пары, которые ОБЯЗАНЫ различаться, потому что несут разный смысл.
MEANINGFUL = [
    ('--gd', '--rd', 'прибыло против перерасхода'),
    ('--accent', '--rd', 'кнопка действия против тревоги'),
    ('--accent', '--gd', 'кнопка действия против плюса'),
    ('--t', '--mt', 'главный текст против вторичного'),
    ('--card', '--pop', 'карточка против меню'),
]


def hex2rgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def srgb2lin(c):
    c /= 255
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def lin2srgb(c):
    c = max(0.0, min(1.0, c))
    v = c * 12.92 if c <= 0.0031308 else 1.055 * (c ** (1 / 2.4)) - 0.055
    return int(round(v * 255))


def rgb2xyz(rgb):
    r, g, b = (srgb2lin(v) for v in rgb)
    return (0.4124 * r + 0.3576 * g + 0.1805 * b,
            0.2126 * r + 0.7152 * g + 0.0722 * b,
            0.0193 * r + 0.1192 * g + 0.9505 * b)


def xyz2lab(xyz):
    wp = (0.95047, 1.0, 1.08883)
    def f(t):
        return t ** (1 / 3) if t > 0.008856 else 7.787 * t + 16 / 116
    fx, fy, fz = (f(xyz[i] / wp[i]) for i in range(3))
    return (116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz))


def lab(h):
    return xyz2lab(rgb2xyz(hex2rgb(h)))


def deltaE(h1, h2):
    """ΔE76 — расстояние в Lab. Меньше 10 — цвета путаются, 2.3 — предел
    различимости для соседних заливок."""
    a, b = lab(h1), lab(h2)
    return math.sqrt(sum((a[i] - b[i]) ** 2 for i in range(3)))


def oklab(h):
    r, g, b = (srgb2lin(v) for v in hex2rgb(h))
    l = 0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b
    m = 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b
    s = 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b
    l_, m_, s_ = l ** (1 / 3), m ** (1 / 3), s ** (1 / 3)
    L = 0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_
    A = 1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_
    B = 0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_
    C = math.sqrt(A * A + B * B)
    Hh = math.degrees(math.atan2(B, A)) % 360
    return L * 100, C * 100, Hh


# ── симуляция цветовой слепоты (Viénot, Brettel & Mollon 1999) ──
RGB2LMS = ((17.8824, 43.5161, 4.11935),
           (3.45565, 27.1554, 3.86714),
           (0.0299566, 0.184309, 1.46709))
LMS2RGB = ((0.0809444479, -0.130504409, 0.116721066),
           (-0.0102485335, 0.0540193266, -0.113614708),
           (-0.000365296938, -0.00412161469, 0.693511405))
DEFICIT = {
    'протанопия':  ((0, 2.02344, -2.52581), (0, 1, 0), (0, 0, 1)),
    'дейтеранопия': ((1, 0, 0), (0.494207, 0, 1.24827), (0, 0, 1)),
    'тританопия':  ((1, 0, 0), (0, 1, 0), (-0.395913, 0.801109, 0)),
}


def mul(mat, v):
    return tuple(sum(mat[i][j] * v[j] for j in range(3)) for i in range(3))


def simulate(h, kind):
    rgb = [srgb2lin(v) * 255 for v in hex2rgb(h)]
    lms = mul(RGB2LMS, rgb)
    lms2 = mul(DEFICIT[kind], lms)
    out = mul(LMS2RGB, lms2)
    return '#%02X%02X%02X' % tuple(lin2srgb(max(0.0, c) / 255) for c in out)


def main():
    print('══ ПАЛИТРА В OKLab ══')
    print('  %-12s %-8s %6s %6s %6s   %s' % ('токен', 'цвет', 'светл', 'насыщ', 'тон', 'роль'))
    for k, (h, role) in PALETTE.items():
        L, C, H = oklab(h)
        print('  %-12s %-8s %6.1f %6.1f %6.0f°  %s' % (k, h, L, C, H, role))

    print('\n══ РАЗЛИЧИМОСТЬ ПАР, НЕСУЩИХ РАЗНЫЙ СМЫСЛ ══')
    print('  ΔE меньше 10 — цвета путаются даже при обычном зрении')
    for a, b, why in MEANINGFUL:
        d = deltaE(PALETTE[a][0], PALETTE[b][0])
        mark = '' if d >= 25 else ('  ← близко' if d >= 10 else '  ← СЛИВАЮТСЯ')
        print('  %-34s ΔE %6.1f%s' % (why, d, mark))

    print('\n══ ЦВЕТОВАЯ СЛЕПОТА ══')
    print('  Что видит человек с дефицитом и остаются ли пары различимы.')
    for kind in DEFICIT:
        share = {'протанопия': '~1% мужчин', 'дейтеранопия': '~6% мужчин',
                 'тританопия': 'редко'}[kind]
        print('\n  %s (%s):' % (kind, share))
        for a, b, why in MEANINGFUL:
            ha, hb = PALETTE[a][0], PALETTE[b][0]
            sa, sb = simulate(ha, kind), simulate(hb, kind)
            d0, d1 = deltaE(ha, hb), deltaE(sa, sb)
            drop = 100 - (d1 / d0 * 100) if d0 else 0
            mark = ''
            if d1 < 10:
                mark = '  ← СЛИВАЮТСЯ'
            elif d1 < 20:
                mark = '  ← почти неразличимы'
            print('    %-32s ΔE %5.1f → %5.1f  (−%.0f%%)%s'
                  % (why, d0, d1, drop, mark))

    print('\n══ ЧТО ЭТО ЗНАЧИТ ══')
    print('  Цвет, оставшийся единственным носителем смысла, для части людей')
    print('  смысла не несёт. Проверять надо не «красиво ли», а есть ли')
    print('  у различия ВТОРОЙ признак: знак, форма, подпись, положение.')


if __name__ == '__main__':
    main()
